tied_totals = {score for score in same_total_scores if same_total_scores.count(score) > 1}
for rank, student in enumerate(top_students, start=1):
    note = ""
    if student["總分"] in tied_totals:
        note = (
            f" (同總分比較：國文 {student['國文']}、英文 {student['英文']}、數學 {student['數學']}、自然 {student['自然']}、社會 {student['社會']})"
        )
    print(
        f"第{rank}名：{student['姓名']} - 總分 {student['總分']}，平均 {student['平均']:.2f}" + note
    )